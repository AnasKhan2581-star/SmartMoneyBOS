// The `cycle` study: what was broken, what each fix and change does, and what ships.
//   python research/fetch_klines.py 4h ADA BNB XRP DOGE LTC TRX AVAX DOT   (full 4h history; 1d is already cached)
//   node research/cycle/cycle_report.js > research/cycle/RESULTS_cycle_2026-10.md
'use strict';
const fs = require('fs'), path = require('path');
const L = require('./cycle_lab.js');
const CACHE = path.join(__dirname, '..', 'cache');

const FIXED = { fix: true, floor: 'skip' };
const FLOOR = { ...FIXED, floor72: true };
const BTCLED = { ...FLOOR, gate: 'both', btcExit: true };
const FINAL = { ...BTCLED, scaleAt: 1.85, scaleMinGain: 0 };
const CORE = ['BTC', 'ETH', 'BNB', 'XRP', 'ADA', 'DOGE', 'LINK', 'LTC', 'TRX', 'SOL', 'AVAX', 'DOT'];
const WATCH = ['SUI', 'INJ', 'HBAR', 'ARB', 'ZEC'];

// every coin with >= 4 years of daily history and >= $1M/day median volume, delisted ones included
const stable = /USD|EUR|TRY|BRL|GBP|AUD|RUB|UAH|NGN|BIDR|IDRT|PAX|DAI|BUSD|TUSD|UST|FDUSD|USDP|AEUR|UP$|DOWN$|BULL$|BEAR$/;
const WIDE = fs.readdirSync(CACHE).filter((f) => f.endsWith('_1d.json')).map((f) => f.replace('_1d.json', '')).filter((coin) => {
  if (stable.test(coin)) return false;
  const r = JSON.parse(fs.readFileSync(path.join(CACHE, coin + '_1d.json')));
  if (r.length < 1460) return false;
  const dv = r.map((x) => x[5] * x[4]).sort((a, b) => a - b);
  return dv[Math.floor(dv.length / 2)] >= 1e6;
}).sort();

const BTC1 = L.load('BTC', '1d'), BTC1i = L.indicators(BTC1);
const prep = (coin, tf = '1d') => {
  const c = L.load(coin, tf); if (!c) return null;
  const ind = L.indicators(c);
  return { coin, c, ind, btc: coin === 'BTC' ? null : L.btcAlign(c, ind, BTC1, BTC1i), last: c[c.length - 1].time };
};
const runOn = (k, o) => {
  const oo = k.btc ? { ...o, btc: k.btc } : { ...o, gate: null, btcExit: false };
  const run = L.simulate(k.c, k.ind, oo);
  return { run, s: L.equity(k.c, k.ind, run) };
};
const fake = (k, run) => run.trades.filter((t) => t.exitPrice > k.c[t.exitIdx].high * 1.000001 || t.exitPrice < k.c[t.exitIdx].low * 0.999999).length;

const out = [], say = (s = '') => out.push(s);
const pc = (x) => (x >= 0 ? '+' : '−') + Math.abs(x * 100).toFixed(0) + '%';
const big = (x) => Math.abs(x) >= 100 ? (x >= 0 ? '+' : '−') + Math.abs(x * 100).toExponential(1).replace('e+', '×10^') + '%' : pc(x);
const pp = (x) => (x * 100).toFixed(0) + '%';
const pf = (x) => isFinite(x) ? x.toFixed(2) : '∞';
const row = (a) => '| ' + a.join(' | ') + ' |';
const med = (v) => { const s = v.slice().sort((a, b) => a - b); return s[Math.floor(s.length / 2)]; };

say(`# \`cycle\` (BTC halving playbook) — bug, fixes and rebuild (Oct 2026)\n`);
say(`Generated by \`research/cycle/cycle_report.js\` on ${new Date().toISOString().slice(0, 10)}. Lab = \`research/cycle/cycle_lab.js\`. With every switch off it `
  + `reproduces the engine as it was before this rebuild trade-for-trade (\`node research/cycle/cycle_lab.js parity 1d|4h\`: 12/12 coins on both, `
  + `against \`detector.js\` at 7a0ad64 read from git); with the shipped switches it reproduces today's \`detector.js\` (\`parity-final 1d|4h\`: `
  + `209/209 coins on 1d, 44/44 on 4h). Money: all-in, `
  + `0.1% fee per side, tranche fills spend their share of the program at their own price, every bar marked to market. `
  + `B&H and every window start where the strategy can first trade (after the 200-day warm-up) and run to the last candle (or the delisting).\n`);

// ---------------------------------------------------------------- 1. the bug
say(`## 1. What was broken\n`);
{
  const c = L.load('ADA', '4h'), r = L.oldEngine().detectAll(c, { strategy: 'cycle', longOnly: true });   // the engine as it was
  const imp = r.trades.filter((t) => t.outcome !== 'open' && (t.exitPrice > c[t.exitIdx].high * 1.000001 || t.exitPrice < c[t.exitIdx].low * 0.999999));
  const above = r.trades.filter((t) => t.stop >= t.entry);
  let eq = 1; for (const t of r.trades) eq *= 1 + (t.exitPrice / t.entry * 0.999 / 1.001 - 1) * (t.frac || 1);
  say(`**The screen that was reported — ADAUSDT 4h, all ${c.length.toLocaleString()} bars:** the engine took **${r.trades.length} trades**; **${above.length}** of them `
    + `opened with the stop ABOVE the entry, and **${imp.length}** "sold" at a price the candle never traded (above its high). $1,000 → $${Math.round(1000 * eq).toLocaleString()}.\n`);
  say(`How: a zone entry put the stop at 0.65 × the 200-week MA. When an alt is already far below its 200-week MA (ADA at 0.3× it), that stop is ABOVE `
    + `the price. The next candle's low is "below the stop", so the position closed AT the stop — a price above the whole candle — booking +10% to +110% `
    + `that never existed, then re-entered and did it again. Two smaller faults: the stop was checked AFTER a same-day tranche buy at the close (the low `
    + `happened first), and a stop was always filled at the stop even when the candle opened below it.\n`);
  say(`Four examples from that run:\n`);
  say(row(['entry', 'buy @', 'stop', 'exit candle low–high', '"sold" @', 'booked']));
  say(row(Array(6).fill('---')));
  for (const t of imp.slice(-4)) say(row([new Date(c[t.entryIdx].time * 1000).toISOString().slice(0, 16).replace('T', ' '), t.entry.toPrecision(4), t.stop.toPrecision(4),
    `${c[t.exitIdx].low.toPrecision(4)}–${c[t.exitIdx].high.toPrecision(4)}`, t.exitPrice.toPrecision(4), pc(t.exitPrice / t.entry - 1)]));
  say(`\nThe old engine vs the same rules with the fills fixed (nothing else changed), 1d, full history:\n`);
  say(row(['coin', 'impossible fills (1d)', 'impossible fills (4h)', 'net old engine (1d)', 'net fixed (1d)', 'max DD fixed', 'B&H']));
  say(row(Array(7).fill('---')));
  for (const coin of CORE) {
    const k = prep(coin), k4 = prep(coin, '4h');
    const r0 = runOn(k, {}), r1 = runOn(k, FIXED), f4 = k4 ? fake(k4, runOn(k4, {}).run) : null;
    say(row([coin, fake(k, r0.run), f4 == null ? '—' : f4, big(r0.s.net), pc(r1.s.net), pc(-r1.s.dd), pc(r1.s.bh)]));
  }
}

// ---------------------------------------------------------------- 2. the ladder
const W = WIDE.map((coin) => prep(coin));
const RES = {};
const runAll = (name, o) => (RES[name] = RES[name] || W.map((k) => runOn(k, o).s));
const summary = (name) => {
  const r = RES[name];
  return row([name, r.length, pc(med(r.map((x) => x.net))), pc(-med(r.map((x) => x.dd))), pc(med(r.map((x) => x.edge))),
    r.filter((x) => x.net > 0).length, r.filter((x) => x.edge > 0).length, pp(med(r.map((x) => x.wr))), r.reduce((a, x) => a + x.trades, 0)]);
};
const paired = (a, b) => {
  const A = RES[a], B = RES[b];
  const better = B.filter((x, i) => x.net > A[i].net + 1e-9).length, worse = B.filter((x, i) => x.net < A[i].net - 1e-9).length;
  const ddb = B.filter((x, i) => x.dd < A[i].dd - 1e-9).length, ddw = B.filter((x, i) => x.dd > A[i].dd + 1e-9).length;
  const h = [0, 1].map((hh) => {
    let bt = 0, wt = 0;
    W.forEach((k, i) => {
      const a0 = k.ind.warm, b0 = k.c.length - 1, m = Math.floor((a0 + b0) / 2);
      const g = (eq) => hh ? Math.log(eq[b0] / eq[m]) : Math.log(eq[m] / eq[a0]);
      const d = g(B[i].eq) - g(A[i].eq); if (d > 1e-9) bt++; else if (d < -1e-9) wt++;
    });
    return `${bt}/${wt}`;
  });
  return { better, worse, ddb, ddw, h };
};
runAll('old engine', {}); runAll('fills fixed', FIXED); runAll('+ zone-B floor', FLOOR); runAll('+ BTC-led', BTCLED); runAll('+ half at sell zone (FINAL)', FINAL);
const nDel = W.filter((k) => k.last < Date.UTC(2026, 9, 1) / 1000).length;
say(`\n## 2. Every change, measured on ${W.length} coins (1d, full history, ${nDel} of them delisted)\n`);
say(`Universe: every Binance USDT coin in the cache with ≥ 4 years of daily candles and ≥ $1M/day median volume — delisted coins INCLUDED, `
  + `because a strategy that buys "cheap vs the 200-week MA" is exactly what dying coins punish. Pre-declared test: a change ships only if it `
  + `helps more coins than it hurts, cuts drawdown more often than it adds to it, and holds in BOTH halves of every coin's window.\n`);
say(row(['rules', 'coins', 'median net', 'median max DD', 'median vs B&H', 'profitable', 'beat B&H', 'median WR', 'trades']));
say(row(Array(9).fill('---')));
for (const n of ['old engine', 'fills fixed', '+ zone-B floor', '+ BTC-led', '+ half at sell zone (FINAL)']) say(summary(n));
say(`\nStep by step (each row vs the row before it; "halves" = coins better/worse in the 1st and 2nd half of their window):\n`);
say(row(['step', 'net better / worse', 'max DD better / worse', '1st half', '2nd half']));
say(row(Array(5).fill('---')));
const steps = [['fills fixed', '+ zone-B floor', 'zone entries need price ≥ 0.72 × 200w (zone B\'s documented floor)'],
  ['+ zone-B floor', '+ BTC-led', 'alts follow BTC\'s cycle (entries gated, BTC-bear exit)'],
  ['+ BTC-led', '+ half at sell zone (FINAL)', 'sell half at the first close ≥ 1.85 × 200-day MA, in profit']];
for (const [a, b, label] of steps) { const p = paired(a, b); say(row([label, `${p.better} / ${p.worse}`, `${p.ddb} / ${p.ddw}`, p.h[0], p.h[1]])); }
{ const p = paired('fills fixed', '+ half at sell zone (FINAL)'); say(row(['**all three together, vs fills fixed**', `**${p.better} / ${p.worse}**`, `**${p.ddb} / ${p.ddw}**`, p.h[0], p.h[1]])); }

// ---------------------------------------------------------------- 3. rejected
const REJ = [   // [idea, rules, measured against, why not]
  ['below the floor: enter anyway with a −28% stop', { fix: true, floor: 'rel' }, 'fills fixed', 'more stop-outs; worse than waiting'],
  ['TREND hard exit on a close < 0.9 × 40w MA', { ...FIXED, trendStop: 0.9 }, 'fills fixed', 'a coin flip — helps and hurts equally'],
  ['after a STOP, no re-entry until the 40w MA is reclaimed', { ...FIXED, lockout: true }, 'fills fixed', 'misses the real bottoms'],
  ['after Mayer ≥ 2, exit on the 20-week MA', { ...FIXED, fastExit: 2 }, 'fills fixed', 'whipsaws out of runs that continue'],
  ['trailing exit 40% under the best close', { ...BTCLED, trail: 0.4 }, '+ BTC-led', 'worse than the 40-week exit'],
  ['alts: trend entries only, no accumulation', { ...BTCLED, noAccum: true }, '+ BTC-led', 'no better than accumulating'],
  ['sell the half at 2.4 × 200d (top of the sell zone) instead', { ...BTCLED, scaleAt: 2.4, scaleMinGain: 0 }, '+ BTC-led', 'same direction, about half the benefit'],
  ['alts: complete the program only once BTC has left its bear signal', { ...FINAL, waitBtc: true }, '+ half at sell zone (FINAL)', 'touches 23 coins, slightly worse'],
];
say(`\n## 3. Tried and rejected (same ${W.length} coins)\n`);
say(row(['idea', 'measured against', 'net better / worse', 'max DD better / worse', 'why not']));
say(row(Array(5).fill('---')));
for (const [label, o, base, why] of REJ) {
  const key = 'rej:' + label; runAll(key, o);
  const p = paired(base, key);
  say(row([label, base, `${p.better} / ${p.worse}`, `${p.ddb} / ${p.ddw}`, why]));
}

// ---------------------------------------------------------------- 4. per coin
say(`\n## 4. Per coin — old engine vs FINAL (1d, full history)\n`);
say(row(['coin', 'trades', 'win rate', 'PF', 'net old engine', '**net FINAL**', 'max DD FINAL', 'B&H', 'B&H max DD', 'vs B&H', 'in market']));
say(row(Array(11).fill('---')));
for (const coin of CORE.concat(WATCH)) {
  const k = prep(coin); if (!k || k.c.length < k.ind.warm + 30) { say(row([coin, '—', '', '', '', 'not enough history', '', '', '', '', ''])); continue; }
  const r0 = runOn(k, {}).s, r = runOn(k, FINAL).s;
  say(row([coin, r.trades, pp(r.wr), pf(r.pf), big(r0.net), `**${pc(r.net)}**`, pc(-r.dd), pc(r.bh), pc(-r.bdd), pc(r.edge), pp(r.expo)]));
}

// ---------------------------------------------------------------- 5. 4h == 1d
say(`\n## 5. 4h and 1d now agree\n`);
say(`The persistence rules ("5 days below the 40-week MA") were counted in BARS: on 4h that meant 30 consecutive closes, and one 4h close back above `
  + `reset the count. In March 2020 BTC daily exited on 1 March at −9%; BTC 4h held on and lost −49% in the crash. The rebuilt engine runs the `
  + `playbook on daily candles built from the chart's own bars and draws the result on the chart's timeframe, so the timeframe cannot change the trades:\n`);
say(row(['coin', '1d trades', '4h trades (same dates?)', 'net 1d', 'net on 4h bars', 'max DD 1d', 'max DD on 4h bars']));
say(row(Array(7).fill('---')));
{
  const B4 = L.toDaily(L.load('BTC', '4h')), B4i = L.indicators(B4);
  let same = 0;
  for (const coin of CORE) {
    const k = prep(coin), r1 = runOn(k, FINAL);
    const c4 = L.load(coin, '4h'), d4 = L.toDaily(c4), i4 = L.indicators(d4);
    const rd = L.simulate(d4, i4, coin === 'BTC' ? { ...FINAL, gate: null, btcExit: false } : { ...FINAL, btc: L.btcAlign(d4, i4, B4, B4i) });
    const ok = rd.trades.length === r1.run.trades.length && rd.trades.every((t, j) => d4[t.entryIdx].time === k.c[r1.run.trades[j].entryIdx].time && d4[t.exitIdx].time === k.c[r1.run.trades[j].exitIdx].time);
    if (ok) same++;
    const s4 = L.equity(c4, { ...L.indicators(c4), warm: d4[i4.warm].first }, L.onNative(c4, d4, rd));
    say(row([coin, r1.run.trades.length, `${rd.trades.length} (${ok ? 'yes' : 'NO'})`, pc(r1.s.net), pc(s4.net), pc(-r1.s.dd), pc(-s4.dd)]));
  }
  say(`\n${same}/${CORE.length} coins: identical trade dates. Money differs by a few % only because the 4h equity is marked every 4 hours and a stop fills on the 4h candle that touched it.`);
}

// ---------------------------------------------------------------- 6. caveats
{
  const F = RES['+ half at sell zone (FINAL)'];
  const del = W.map((k, i) => ({ k, s: F[i] })).filter((x) => x.k.last < Date.UTC(2026, 9, 1) / 1000);
  say(`\n## 6. What this still is — read before trusting it\n`);
  say(`- **A long-only cycle system.** Median max drawdown on ${W.length} coins is still ${pc(-med(F.map((x) => x.dd)))} (buy & hold: ${pc(-med(F.map((x) => x.bdd)))}). On the median alt it still loses `
    + `(${pc(med(F.map((x) => x.net)))}), it just loses far less than holding (median B&H ${pc(med(F.map((x) => x.bh)))}). It is a BTC system that alts can borrow, not an alt picker.`);
  say(`- **Delisted coins (${del.length}):** median net ${pc(med(del.map((x) => x.s.net)))}, median B&H ${pc(med(del.map((x) => x.s.bh)))}.`);
  say(`- **The half at the sell zone costs the biggest runs.** BTC 2020–21: half sold at $22.8k in Dec 2020, the rest at the Pi-Cycle top ($59.9k). `
    + `ADA 2020–21: half at $0.081, rest at $1.10. It pays on the many runs that round-trip (most alts after 2021) — 2nd-half results above.`);
  say(`- **Every window ends in Oct 2026**, inside a BTC drawdown, which is a bad moment to mark a long-only system.`);
  say(`- These are backtests on candle closes with 0.1% fees; no slippage beyond a stop filled at the open when it gaps.`);
}
