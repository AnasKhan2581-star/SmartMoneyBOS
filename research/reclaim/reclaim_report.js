/*
 * The report of the reclaim-zone study: node research/reclaim/reclaim_lab.js report > research/reclaim/RESULTS_reclaim_2026-11.md
 * Needs: reclaim_lab.js run / run gross / run slip2, broad and fresh (each with gross and slip2), diag_1h.js, regime_1h.js.
 * Every sentence that states a comparison is checked against the numbers (need()), so a re-run that changes a conclusion
 * stops the report instead of printing a stale claim.
 */
'use strict';
const fs = require('fs'), path = require('path');
const { DIR, COINS } = require('./data.js');
const L = require('./reclaim_lab.js');
const TFS = L.TFS;
const J = (f) => JSON.parse(fs.readFileSync(path.join(DIR, f)));
const sg = (x, d = 2) => (x === null || x === undefined || Number.isNaN(x) ? '–' : (x >= 0 ? '+' : '−') + Math.abs(x * 100).toFixed(d) + '%');
const pv = (p) => (p === null || p === undefined ? '–' : p < 0.001 ? '< 0.001' : p.toFixed(3));
const pf = (x) => (x === Infinity || x === null ? '∞' : x === undefined ? '–' : x.toFixed(2));   // JSON keeps Infinity as null
const coin = (s) => s.replace('USDT', '');
function need(cond, what) { if (!cond) throw new Error(`report claim no longer holds: ${what}`); }

function pooledTf(run, nm, tf, half) {
  const real = [], copies = [];
  for (const [k, row] of Object.entries(run.rows[nm])) {
    if (!k.endsWith('|' + tf) || k.startsWith('XAUUSD')) continue;
    row.real[half].forEach((x, i) => { real.push(x); copies.push(row.ctrl[half][i] || []); });
  }
  return L.vsRandom(real, copies);
}

function report() {
  const run = { spot: J('run_spot.json'), gross: J('run_gross.json'), slip2: J('run_slip2.json') };
  const wide = {};
  for (const w of ['broad', 'fresh']) for (const c of ['spot', 'gross', 'slip2']) wide[`${w}|${c}`] = J(`${w}_${c}.json`);
  const diag = J('diag1h_spot.json'), reg = J('regime1h.json');
  const ch = run.spot.choice, FINAL = ch.final, B = L.BASE;
  const out = [];
  const w = (s = '') => out.push(s);

  w('# The reclaim zone: a sudden drop, a close above the strong high, the first tap of the untouched bottom (Nov 2026)');
  w();
  w(`Generated by \`node research/reclaim/reclaim_lab.js report\` on ${new Date().toISOString().slice(0, 10)}. Research only: the app and the bot don't use it.`);
  w('Data: Binance spot, every 3m candle from each coin\'s listing to 25 Nov 2026 00:00 UTC; 15m, 1h, 4h and 1d are built from them, so every timeframe of a coin covers the same history.');
  w();
  w('## The rules');
  w();
  w('The base rules were fixed from the trading logic before any result was seen (README.md has the reasoning). Everything is counted in the chart\'s own candles and its own ATR (Wilder, 14):');
  w(`- **Strong high**: the highest high of the ${B.M} candles before it.`);
  w(`- **Sudden drop**: within ${B.K} candles the low is ≥ ${B.D} ATR under the high (the ATR of the candle before the high), and it trades under the lowest low of those ${B.M} candles (the range's stops and liquidations).`);
  w(`- **Reclaim**: a candle closes above the strong high within ${B.Rx * B.K} candles of the low.`);
  w('- **Zone**: the bottom third of the drop, untouched between leaving it and the reclaim.');
  w(`- **Trade**: a limit buy at the top of the zone on its first touch (within ${B.E} candles of the reclaim); stop ${B.buf} ATR under the drop's low; target the highest high since the reclaim; out after ${B.T} candles.`);
  w('- **Fills**: a limit buy fills at its price (or a lower open); on the fill candle only the stop can fill; stops fill at the stop or a lower open.');
  w('- **Costs**: 0.1% a side, plus 0.05% (BTC, ETH, SOL) or 0.15% (the rest) slippage on stops and timed exits.');
  w('- **Control**: each trade\'s exact order (depth under the price, stop and target, all in ATR) placed at 50 random times in the same half of the same chart. *p* is the share of random sets (one copy per trade) that did as well.');
  w();
  w(`**The choice** (the first half of each coin's history only). Each change from the base was kept if it raised the first-half average trade on a majority of the timeframes with ≥ 10 first-half trades. Only 3m and 15m had that many. Kept: **${ch.kept.join(', ')}**. The chosen rules:`);
  const desc = { K6: `the drop within ${FINAL.K} candles`, M20: `the strong high is the highest of ${FINAL.M} candles`, Rx6: `the reclaim within ${FINAL.Rx * FINAL.K} candles`,
    f50: 'the zone is the bottom HALF of the drop', f25: 'the zone is the bottom quarter', T300: `out after ${FINAL.T} candles`, T50: `out after ${FINAL.T} candles`,
    mitig: 'the zone may have been revisited before the reclaim', D3: `a drop of ≥ ${FINAL.D} ATR`, D8: `a drop of ≥ ${FINAL.D} ATR`, K24: `the drop within ${FINAL.K} candles`,
    M150: `the strong high is the highest of ${FINAL.M} candles`, Rx1: `the reclaim within ${FINAL.Rx * FINAL.K} candles`, E150: `the zone waits ${FINAL.E} candles`, E2000: `the zone waits ${FINAL.E} candles`,
    nosweep: 'the drop needn\'t take the range\'s low', halfbos: 'the reclaim is a close above the drop\'s middle', confirm: 'buy a close back above the zone after the tap', ride: 'half at the target, the rest trails' };
  w(ch.kept.map((k) => desc[k] || k).join('; ') + '.');
  w();

  // ---------------------------------------------------------------- how often
  w('## How often the shape appears (the 8 coins)');
  w();
  w('| | candles | setups, base | trades, base | setups, chosen | trades, chosen | one setup per … candles (base) | median stop, chosen |');
  w('|---|---|---|---|---|---|---|---|');
  const rate = {};
  for (const tf of TFS) {
    let bars = 0, pb = 0, pf2 = 0, tb = 0, tf2 = 0;
    for (const s of COINS) {
      const rb = run.spot.byChart.base[`${s}|${tf}`], rf = run.spot.rows.final ? run.spot.rows.final[`${s}|${tf}`] : null;
      if (!rb || !rf) continue;
      bars += rf.bars; pb += rb.pats; tb += rb.all.n; pf2 += rf.pats; tf2 += rf.all.n;
    }
    const risks = run.spot.trades.final.filter((t) => t.tf === tf && t.sym !== 'XAUUSD').map((t) => t.risk).sort((a, b) => a - b);
    rate[tf] = pb ? bars / pb : Infinity;
    w(`| ${tf} | ${bars.toLocaleString('en-US')} | ${pb} | ${tb} | ${pf2} | ${tf2} | ${pb ? Math.round(bars / pb).toLocaleString('en-US') : '–'} | ${risks.length ? sg(risks[risks.length >> 1]).replace('+', '') : '–'} |`);
  }
  w();
  need(rate['3m'] > 10000 && rate['15m'] > 10000, 'the shape is rarer than one setup per 10,000 candles on 3m and 15m');
  w('The shape is about equally rare per candle on every timeframe, so a daily chart (about 3,400 candles a coin since 2017) almost never shows it: your chart is a 27-year view with one. 4h and 1d are judged on wider coin lists below.');
  w();

  // ---------------------------------------------------------------- the 8 coins
  for (const nm of ['final', 'base']) {
    w(`## The 8 coins: ${nm === 'final' ? 'the chosen rules' : 'the base rules'}, per timeframe`);
    w();
    w(`Pooled over PAXG, BTC, ETH, SOL, STX, XRP, BNB and ARB. ${nm === 'final' ? 'First half = where these rules were chosen' : 'These rules were fixed before any data was run'}; **second half = the judge**.`);
    w();
    w('| | trades 1st / 2nd | avg trade 1st | **avg trade 2nd** | random times 2nd | *p* | win rate 2nd | PF 2nd | before costs 2nd (random) | double slippage 2nd |');
    w('|---|---|---|---|---|---|---|---|---|---|');
    for (const tf of TFS) {
      const a = pooledTf(run.spot, nm, tf, 'first'), b = pooledTf(run.spot, nm, tf, 'second');
      const g = pooledTf(run.gross, nm, tf, 'second'), s2 = pooledTf(run.slip2, nm, tf, 'second');
      w(`| ${tf} | ${a.real.n || 0} / ${b.real.n || 0} | ${sg(a.real.avg)} | **${sg(b.real.avg)}** | ${sg(b.rand)} | ${pv(b.p)} | ${b.real.n ? Math.round(b.real.wr * 100) + '%' : '–'} | ${b.real.n ? pf(b.real.pf) : '–'} | ${sg(g.real.avg)} (${sg(g.rand)}) | ${sg(s2.real.avg)} |`);
    }
    w();
  }
  for (const tf of ['3m', '15m']) {
    const b = pooledTf(run.spot, 'final', tf, 'second'), g = pooledTf(run.gross, 'final', tf, 'second');
    need(b.real.avg < 0 && b.p > 0.1 && g.real.avg < g.rand + 0.001, `the chosen rules on ${tf} lose and match random times in the second half`);
  }
  const f1 = pooledTf(run.spot, 'final', '1h', 'first'), f2 = pooledTf(run.spot, 'final', '1h', 'second');
  need(f1.real.avg > 0.01 && f2.real.avg < 0 && f2.p > 0.5, 'the chosen rules on 1h look good in the first half and lose in the second');
  const r3 = run.spot.trades.final.filter((t) => t.tf === '3m').map((t) => t.risk).sort((x, y) => x - y);
  need(r3[r3.length >> 1] < 0.005, 'the median 3m stop is under 0.5%, so 0.2% of fees is about half of it');
  w('On 3m and 15m the zone tap is no better than the same order at a random time, even before costs. Costs then make every row a loss: on 3m the 0.2% of fees alone is half the median stop. The chosen rules\' 1h row looks good in the first half and loses in the second; the base rules have only 9 and 11 trades on 1h, and 0–2 on 4h and 1d.');
  w();

  // ---------------------------------------------------------------- the variants
  w('## Every change from the base rules (spot costs: avg trade, trades in brackets; only the first halves chose)');
  w();
  w('| change | 3m 1st | 3m 2nd | 15m 1st | 15m 2nd | 1h 1st | 1h 2nd | won / counted |');
  w('|---|---|---|---|---|---|---|---|');
  for (const [nm, v] of Object.entries(run.spot.perVar)) {
    const c = (tf, h) => (v[tf][h].n ? `${sg(v[tf][h].avg)} (${v[tf][h].n})` : '–');
    w(`| ${nm}${ch.kept.includes(nm) ? ' **kept**' : ''} | ${c('3m', 'first')} | ${c('3m', 'second')} | ${c('15m', 'first')} | ${c('15m', 'second')} | ${c('1h', 'first')} | ${c('1h', 'second')} | ${nm === 'base' ? '' : `${ch.wins[nm]} / ${ch.cnt[nm]}`} |`);
  }
  w();
  const allNeg = Object.values(run.spot.perVar).every((v) => v['3m'].second.avg < 0 && v['3m'].first.avg < 0);
  need(allNeg, 'every variant loses on 3m in both halves');
  const pos15 = Object.entries(run.spot.perVar).filter(([, v]) => v['15m'].second.avg >= 0).map(([k]) => k);
  need(pos15.length === 1 && pos15[0] === 'E150', 'on 15m in the second half only E150 is positive');
  w('Every variant loses on 3m in both halves, and on 15m in the second half all but one do (E150, 35 trades).');
  w();

  // ---------------------------------------------------------------- per coin
  w('## Per coin and timeframe: the chosen rules, all history (Compare\'s columns)');
  w();
  w('All-in on each trade, marked on candle closes. vs B&H = how much richer than holding the coin over the same candles.');
  w();
  w('| coin | tf | Trades | Net P/L | vs B&H | PF | Max DD | Win rate | In mkt | Yrs |');
  w('|---|---|---|---|---|---|---|---|---|---|');
  for (const s of COINS.concat(['XAUUSD'])) for (const tf of TFS) {
    const r = run.spot.rows.final[`${s}|${tf}`];
    if (!r) continue;
    const e = r.all, vs = (1 + e.net) / (1 + e.bh) - 1;
    w(`| ${coin(s)} | ${tf} | ${e.n} | ${sg(e.net, 1)} | ${sg(vs, 1)} | ${e.n ? pf(e.pool.pf) : '–'} | ${e.n ? sg(e.dd, 1) : '–'} | ${e.n ? Math.round(e.pool.wr * 100) + '%' : '–'} | ${sg(e.inMkt, 1).replace('+', '')} | ${e.yrs.toFixed(1)} |`);
  }
  w();
  w('XAUUSD is spot gold, daily candles from 2003 (data/xauusd_1d.csv), an extra beside PAXG.');
  w();

  // ---------------------------------------------------------------- wide lists
  w('## 1h, 4h and 1d on wider lists');
  w();
  w('Same rules, same control. **The 103-coin list** is your Compare list (CMP_DEFAULT). **Fresh coins** are the 295 other USDT coins trading on Binance spot today, without stablecoins, wrapped copies, gold or stock tokens: no rule was ever chosen on them. `big` is the chosen rules with a fall of ≥ 8 ATR, a neighbour that stood out on the 103-coin 1h list, so the fresh coins are its only clean test. Both lists are today\'s coins: coins that died are missing, which flatters any long strategy.');
  w();
  w('| list | rules | tf | trades 1st / 2nd | avg trade 1st (random, *p*) | **avg trade 2nd (random, *p*)** | median trade 2nd | before costs 2nd | double slippage 2nd | coins with trades / ahead |');
  w('|---|---|---|---|---|---|---|---|---|---|');
  for (const lst of ['broad', 'fresh']) for (const [k, v] of Object.entries(wide[`${lst}|spot`].rows)) {
    const [nm, tf] = k.split('|'), g = wide[`${lst}|gross`].rows[k], s2 = wide[`${lst}|slip2`].rows[k];
    const pos = v.coins.filter((c) => c.n > 0);
    const c = (h) => (h.real.n ? `${sg(h.real.avg)} (${sg(h.rand)}, ${pv(h.p)})` : '–');
    w(`| ${lst === 'broad' ? '103 coins' : 'fresh 295'} | ${nm} | ${tf} | ${v.first.real.n || 0} / ${v.second.real.n || 0} | ${c(v.first)} | **${c(v.second)}** | ${v.second.real.n ? sg(v.second.real.med) : '–'} | ${v.second.real.n ? sg(g.second.real.avg) : '–'} | ${v.second.real.n ? sg(s2.second.real.avg) : '–'} | ${pos.length} / ${pos.filter((x) => x.sum > 0).length} |`);
  }
  w();
  const bf = wide['broad|spot'].rows['final|1h'], ff = wide['fresh|spot'].rows['final|1h'], fb = wide['fresh|spot'].rows['big|1h'];
  need(bf.first.p < 0.01 && bf.second.p < 0.01, 'the chosen rules beat random times on the 103-coin 1h list in both halves');
  need(ff.first.p < 0.01 && ff.second.p > 0.1, 'on the fresh coins the chosen rules beat random times in the first half only');
  need(fb.first.p < 0.01 && fb.second.p < 0.05 && fb.second.real.med < 0, 'big beats random on the fresh coins in both halves, with a losing median trade in the second');
  w('The chosen rules beat random times on 1h of the 103-coin list in both halves, but on the fresh coins only in the first half of their history. The 8-ATR version beats random times on the fresh coins in both halves, with a losing median trade in the second. 4h and 1d show nothing that holds in both halves on both lists.');
  w();

  // ---------------------------------------------------------------- 1h detail
  w('## 1h on the 103-coin list: what carries it');
  w();
  const all = diag.all;
  w(`- The chosen rules: ${all.n} trades, average ${sg(all.avg)}, median ${sg(all.med)}, ${Math.round(all.wr * 100)}% winners. The top 5 coins (${diag.byCoin.slice(0, 5).map((x) => coin(x[0])).join(', ')}) give ${Math.round(diag.byCoin.slice(0, 5).reduce((s, x) => s + x[1], 0) / diag.byCoin.reduce((s, x) => s + x[1], 0) * 100)}% of the summed returns; ${diag.byCoin.filter((x) => x[1] > 0).length} of ${diag.byCoin.length} coins come out ahead.`);
  w('- One rule moved at a time (spot costs):');
  w();
  w('| rules | trades 1st | avg 1st | trades 2nd | avg 2nd |');
  w('|---|---|---|---|---|');
  for (const [nm, v] of Object.entries(diag.nb)) w(`| ${nm} | ${v.h1.n} | ${sg(v.h1.avg)} | ${v.h2.n} | ${sg(v.h2.avg)} |`);
  w();
  w('**By calendar year and market** (BTC\'s close at the fill against its 50-day average; avg trade, trades):');
  w();
  const years = [...new Set(Object.values(reg).flatMap((r) => Object.keys(r.years)))].sort();
  w(`| list · rules | BTC over its 50d | under | ${years.join(' | ')} |`);
  w(`|---|---|---|${years.map(() => '---').join('|')}|`);
  for (const [k, r] of Object.entries(reg)) {
    const [lst, nm] = k.split('|');
    const cell = (y) => { const v = r.years[y]; if (!v) return '–'; const a = [v.up, v.down].filter((x) => x.n); const n = a.reduce((s, x) => s + x.n, 0); return n ? `${sg(a.reduce((s, x) => s + x.avg * x.n, 0) / n, 1)} (${n})` : '–'; };
    w(`| ${lst === 'broad' ? '103' : 'fresh'} · ${nm} | ${sg(r.up50.avg)} (${r.up50.n}) | ${sg(r.down50.avg)} (${r.down50.n}) | ${years.map(cell).join(' | ')} |`);
  }
  w();
  const y26 = (k) => { const v = reg[k].years['2026']; const a = [v.up, v.down].filter((x) => x.n), n = a.reduce((s, x) => s + x.n, 0); return a.reduce((s, x) => s + x.avg * x.n, 0) / n; };
  need(y26('fresh|final') < 0 && y26('fresh|big') < 0, 'both 1h versions lose in 2026 on the fresh coins');
  need(reg['fresh|big'].years['2026'].up.avg < 0, 'the 8-ATR version loses in 2026 on the fresh coins even with BTC over its 50-day average');
  w('Trades with BTC above its 50-day average did better everywhere, but in 2026 both versions lose on the fresh coins, even with BTC above it. This split was added after both lists had been seen.');
  w();
  process.stdout.write(out.join('\n') + '\n');
}

module.exports = { report };
